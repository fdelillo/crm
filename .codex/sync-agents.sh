#!/bin/sh
# Generates the Codex custom agents (.codex/agents/*.toml) from the Claude Code agents
# (.claude/agents/*.md), so both tools follow one set of rules. The .md files are the only source:
# each .toml only carries the name, the description and an instruction to read its .md.
#
#   sh .codex/sync-agents.sh          regenerate .codex/agents/
#   sh .codex/sync-agents.sh --check  fail if .codex/agents/ is out of date (run by `make lint`)
#
# Codex agent format: https://learn.chatgpt.com/docs/agent-configuration/subagents
set -eu

cd "$(dirname "$0")/.."
src=.claude/agents
dst=.codex/agents

# generate <dir>: writes one .toml per agent of $src into <dir>.
generate() {
	out=$1
	for md in "$src"/*.md; do
		awk -v file="$md" '
			function fail(msg) { print file ": " msg > "/dev/stderr"; bad = 1; exit 1 }
			NR == 1 { if ($0 != "---") fail("no frontmatter"); next }
			$0 == "---" { done = 1; exit }
			/^name: /        { name = substr($0, 7) }
			/^description: / { desc = substr($0, 14) }
			/^tools: /       { tools = ", " substr($0, 8) "," }
			/^model: /       { model = substr($0, 8) }
			END {
				if (bad) exit 1
				if (!done) fail("unterminated frontmatter")
				if (name == "" || desc == "" || tools == "") fail("needs name, description and tools")
				if (index(desc, "\047") || index(desc, "\n")) fail("description cannot contain a single quote")
				expected = file; sub(/^.*\//, "", expected); sub(/\.md$/, "", expected)
				if (name != expected) fail("name \"" name "\" differs from the file name")

				# What the agent may change. Codex cannot remove tools from a custom agent, so the
				# limits of the `tools:` line become an instruction.
				edits = index(tools, " Edit,") > 0
				writes = index(tools, " Write,") > 0
				shell = index(tools, " Bash,") > 0
				if (edits && shell)
					limits = "Podés editar archivos y correr comandos, dentro del alcance que te da ese archivo."
				else if (writes && !shell)
					limits = "No editás código ni corrés comandos: solo leés el repositorio y escribís los documentos de diseño que ese archivo te asigna."
				else if (!writes && !edits && shell)
					limits = "No modificás ningún archivo del repositorio: solo corrés comandos de lectura o de verificación (tests, lint, `git diff`, `git log`)."
				else
					fail("no capability rule for tools:" tools)

				# The Claude model of each agent becomes a reasoning effort: design and review
				# (opus) think the most; implementation (sonnet) keeps the session default.
				effort = (model == "opus") ? "xhigh" : (model == "sonnet") ? "high" : ""

				print "# Generated by .codex/sync-agents.sh from " file ". Do not edit: run `make codex-agents`."
				print "name = \"" name "\""
				print "description = \047" desc "\047"
				if (effort != "") print "model_reasoning_effort = \"" effort "\""
				print "developer_instructions = \047\047\047"
				print "Tus instrucciones completas están en `" file "`, desde la raíz del repositorio."
				print "Antes de cualquier otra cosa, leé ese archivo entero y seguilo como si fuera este mensaje:"
				print "prevalece sobre cualquier regla genérica tuya. Si no lo podés leer, frená y avisá; no sigas"
				print "sin él."
				print ""
				print "Ese archivo está escrito para Claude Code. Al aplicarlo en Codex:"
				print ""
				print "- " limits
				print "  Esto reemplaza a la línea `tools:` de su encabezado, que Codex no aplica por su cuenta."
				print "- Las herramientas que nombra (Read, Grep, Glob, Write, Edit, Bash, WebSearch, WebFetch) son"
				print "  tus equivalentes de lectura, búsqueda, edición, shell y web. La línea `model:` no aplica."
				print "- Donde dice que leas `CLAUDE.md`, leé también `AGENTS.md`."
				print "\047\047\047"
			}
		' "$md" > "$out/$(basename "$md" .md).toml"
	done
}

if [ "${1:-}" = "--check" ]; then
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	generate "$tmp"
	if ! diff -r "$tmp" "$dst" > /dev/null 2>&1; then
		diff -r "$tmp" "$dst" || true
		echo "$dst is out of date with $src: run 'make codex-agents'" >&2
		exit 1
	fi
elif [ $# -eq 0 ]; then
	mkdir -p "$dst"
	rm -f "$dst"/*.toml
	generate "$dst"
else
	echo "usage: $0 [--check]" >&2
	exit 2
fi
